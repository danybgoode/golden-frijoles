#!/usr/bin/env node
// render-plugin-release.mjs — the release install.md describes, as a module the site can import
// (account-from-the-terminal S1.1, canvas First run frame 2).
//
//   node scripts/render-plugin-release.mjs          write apps/web/lib/plugin-release.generated.ts
//   node scripts/render-plugin-release.mjs --check  exit 1 if it is stale
//
// install.md names the plugin release and lists a SHA-256 per file. Those come from `skills/SHA256SUMS`
// (written by `skills/scripts/plugin-checksums.mjs`) and the versions in `plugin.json` and the CLI's
// `package.json` — never typed by hand. The site cannot read `skills/` at runtime (it is outside the app),
// so this copies them into `apps/web/lib`, and `plugin-release.test.ts` fails the unit suite while the copy
// and its sources disagree.
//
// Zero deps — Node 18+.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const TARGET = 'apps/web/lib/plugin-release.generated.ts';

export function renderPluginRelease(root = ROOT) {
  const plugin = JSON.parse(readFileSync(join(root, 'skills/plugins/golden-frijoles/.claude-plugin/plugin.json'), 'utf8'));
  const cli = JSON.parse(readFileSync(join(root, 'packages/cli/package.json'), 'utf8'));
  const sums = readFileSync(join(root, 'skills/SHA256SUMS'), 'utf8');
  return `// GENERATED by scripts/render-plugin-release.mjs from skills/SHA256SUMS, plugin.json and
// packages/cli/package.json — do not edit by hand. Regenerate: node scripts/render-plugin-release.mjs

export const PLUGIN_VERSION = ${JSON.stringify(plugin.version)}
export const CLI_VERSION = ${JSON.stringify(cli.version)}
/** \`shasum -a 256 -c\` format: one \`<hex>  <path>\` line per plugin file, paths from the skills repo root. */
export const PLUGIN_SHA256SUMS = ${JSON.stringify(sums)}
`;
}

function main(argv) {
  const rendered = renderPluginRelease();
  const target = join(ROOT, TARGET);
  if (argv[0] === '--check') {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {}
    if (current === rendered) return 0;
    console.error(`render-plugin-release: ${TARGET} is stale. Run: node scripts/render-plugin-release.mjs`);
    return 1;
  }
  writeFileSync(target, rendered);
  console.log(`render-plugin-release: wrote ${TARGET}.`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
